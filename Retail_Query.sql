--calculate month over month sale growth
SELECT EXTRACT(YEAR FROM sale_date) AS year,
		EXTRACT(MONTH FROM sale_date) AS month,
		SUM(total_sale) as total_Sale ,
		LAG(SUM(total_sale),1,0) 
		OVER(ORDER BY  EXTRACT(YEAR FROM sale_date), EXTRACT(MONTH FROM sale_date)) 
		AS previous_month_sale,
		ROUND((SUM(total_sale)-
		LAG(SUM(total_sale),1,0) 
		OVER(ORDER BY  EXTRACT(YEAR FROM sale_date), EXTRACT(MONTH FROM sale_date)))*100/
		LAG(SUM(total_sale)) 
		OVER(ORDER BY EXTRACT(YEAR FROM sale_date),EXTRACT(MONTH FROM sale_date)),2)AS GROWTH
FROM retail_sales
GROUP BY 1,2 ORDER BY 1,2;		


